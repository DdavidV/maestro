  defp step(assigns) do
    ~H"""
    <li class={"m-step m-step-#{@step.status}"}>
      <div class="m-step-header">
        <span class="m-step-index">{@index}</span>
        <h4>{@step.name}</h4>
        <span :if={@step.client} class="m-client">{@step.client}</span>
        <span :if={@step.duration} class="m-toc-meta m-duration">
          {format_duration(@step.duration)}
        </span>
        <.status_icon status={@step.status} />
      </div>
      <.failure_row :if={@step.dispatch_error} failure={@step.dispatch_error} />
      <p :if={@step.assertions == [] and is_nil(@step.dispatch_error)} class="m-no-assertions">
        (no assertions)
      </p>
      <.assertion :for={assertion <- @step.assertions} assertion={assertion} />
      <details :if={payload = request_payload(@step)} class="m-request">
        <summary>Request payload</summary>
        <pre>{payload}</pre>
      </details>
    </li>
    """
  end

  attr :assertion, :map, required: true

