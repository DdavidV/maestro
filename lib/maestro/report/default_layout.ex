        </div>
        <h1>Test run report</h1>
        <p class="m-run-id">Run <code>{@model.run_id}</code></p>
        <p class="m-generated-at">Generated {format_datetime(@model.generated_at)}</p>
        <p class="m-run-duration">Duration {format_duration(@model.summary.duration)}</p>
      </div>
      <div class="m-header-status">
        <div class={"m-badge m-badge-lg m-badge-#{@model.status}"}>{@model.status}</div>
        <ul class="m-summary">
          <li>Total suites: {@model.summary.total}</li>
          <li class="m-summary-ok">Passed: {@model.summary.ok}</li>
          <li class="m-summary-error">Failed: {@model.summary.error}</li>
        </ul>
      </div>
    </header>

    <section class="m-stats" aria-label="Run statistics">
      <.stat label="Suites" passed={@model.summary.ok} total={@model.summary.total} />
      <.stat label="Testcases" passed={@counts.testcases.ok} total={@counts.testcases.total} />
      <.stat label="Steps" passed={@counts.steps.ok} total={@counts.steps.total} />
      <.stat label="Assertions" passed={@counts.assertions.ok} total={@counts.assertions.total} />
    </section>
    """
  end

  attr :label, :string, required: true
  attr :passed, :integer, required: true
  attr :total, :integer, required: true

  defp stat(assigns) do
    assigns = assign(assigns, :percent, percent(assigns.passed, assigns.total))

    ~H"""
    <div class="m-stat">
      <div class="m-stat-label">{@label}</div>
      <div class="m-stat-value">
        {@passed}<span class="m-stat-total">/{@total}</span>
      </div>
      <div class="m-progress" role="img" aria-label={"#{@percent}% passed"}>
        <div
          class={["m-progress-bar", @passed < @total && "m-progress-bar-partial"]}
          style={"width: #{@percent}%"}
        >
        </div>
      </div>
      <div class="m-stat-hint">{@percent}% passed</div>
    </div>
    """
  end

  attr :model, :map, required: true

