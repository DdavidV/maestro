  defp counts(model) do
    testcases = Enum.flat_map(model.suites, & &1.testcases)
    steps = Enum.flat_map(testcases, & &1.steps)
    assertions = Enum.flat_map(steps, & &1.assertions)

    %{
      testcases: tally(testcases),
      steps: tally(steps),
      assertions: tally(assertions)
    }
  end

  defp tally(items), do: %{ok: Enum.count(items, &(&1.status == :ok)), total: length(items)}

  defp testcase_tally([]), do: "no testcases"

  defp testcase_tally(testcases) do
    %{ok: ok, total: total} = tally(testcases)
    "#{ok}/#{total} testcases passed"
  end

  defp pretty(term), do: inspect(term, pretty: true)

  defp percent(_passed, 0), do: 0
  defp percent(passed, total), do: round(passed * 100 / total)

  defp format_duration(duration), do: Maestro.Util.format_duration(duration)

  defp format_datetime(%DateTime{} = dt), do: Calendar.strftime(dt, "%Y-%m-%d %H:%M:%S UTC")
  defp format_datetime(other), do: to_string(other)

  # The step's rendered request payload, pretty-printed for the collapsible
  # "Request payload" panel; `nil` when the step never got far enough to
  # render one (e.g. an interpolation failure).
  defp request_payload(%{rendered: %{"payload" => payload}}) when not is_nil(payload) do
    case Jason.encode(payload, pretty: true) do
      {:ok, json} -> json
      {:error, _reason} -> inspect(payload, pretty: true)
    end
  end

  defp request_payload(_step), do: nil

