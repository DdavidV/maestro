      </div>
      <.suite_toc suite={@suite} />
      <p :if={@suite.testcases == []} class="m-empty">No testcases have finished yet.</p>
      <.testcase :for={testcase <- @suite.testcases} testcase={testcase} />
      <a href="#top" class="m-back-to-top">↑ Back to top</a>
