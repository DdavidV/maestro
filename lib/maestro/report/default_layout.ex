        <li :if={@failure.kind == :assertion_mismatch}>expected: {pretty(@failure.expected)}</li>
        <li :if={@failure.kind == :assertion_mismatch}>actual: {pretty(@failure.actual)}</li>
        <li :if={@failure.kind == :dispatch_error}>details: {inspect(@failure.details)}</li>
      </ul>
    </div>
    """
  end

